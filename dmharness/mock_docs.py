"""Шаблоны документов для MockLLM. Все числа берутся из запроса и observation инструментов."""
from __future__ import annotations

import re

from .guardrails import REQ_ID


def _n(x: int | float) -> str:
    return f"{x:,}".replace(",", " ")


def research(p, obs, artifacts, faulty):
    cats, ests = obs["catalog_lookup"], obs["estimate_load"]
    rows = "\n".join(
        f"| {c['source']} | {c['system']} | {_n(c['rows_per_day'])} | {c['avg_row_bytes']} Б | {c['owner']} | "
        f"{'да' if c['pii'] else 'нет'} |" for c in cats)
    load = "\n".join(
        f"| {c['source']} | {e['avg_eps']} | {e['peak_eps']} | {e['gb_per_day']} | {e['raw_tb']} | "
        f"{e['stored_tb_compressed']} |" for c, e in zip(cats, ests))
    total = round(sum(e["stored_tb_compressed"] for e in ests), 2)
    pii = [c["source"] for c in cats if c["pii"]]
    return f"""# Research: {p['title']}

## Источники
| Источник | Система | Строк/сутки | Размер строки | Владелец | PII |
|---|---|---|---|---|---|
{rows}

## Оценка нагрузки
| Источник | events/s (средн.) | events/s (пик ×{p['peak_factor']:g}) | ГБ/сутки | Сырое хранение, ТБ ({p['retention_days']} дн.) | Сжатое, ТБ |
|---|---|---|---|---|---|
{load}

Суммарное хранение (сжатое): {total} ТБ

Допущение: {ests[0]['assumption']}.

## Риски и допущения
- Источники с PII: {', '.join(pii) if pii else 'нет'} — требуется маскирование и ограничение доступа.
- Смешанные системы-источники (Kafka, Greenplum, Hadoop): разные гарантии доставки и семантика времени.
- SLA свежести {p['freshness_sla_seconds']} с требует контроля лага на всём пути, а не только в хранилище.
- Допущение: схема источников стабильна; эволюция схемы обрабатывается отдельной фичей.
"""


def cjm(p, obs, artifacts, faulty):
    personas = obs["list_personas"][0]["personas"]
    ptxt = "\n".join(f"- **{x['name']}** — цель: {x['goal']} Боли: {'; '.join(x['pains'])}." for x in personas)
    return f"""# CJM: {p['title']}

## Персоны
{ptxt}

## Карта пути (CJM)
| Этап | Действие пользователя | Боль сейчас | Целевое решение фичи | Метрика |
|---|---|---|---|---|
| Идея | Формулирует потребность в витрине | Непонятно, с чего начать | Шаблон YAML-описания витрины | time-to-first-datamart ≤ 1 дня |
| Описание | Описывает источники, ключ, SLA, DQ | Копипаст загрузчиков | Декларативная конфигурация + валидация | 90 % витрин без кастомного кода загрузки |
| Запуск | Деплоит витрину | Ручная настройка загрузки | Автогенерация DDL и инкрементальной загрузки | 0 ручных шагов после коммита |
| Контроль качества | Смотрит результаты проверок | Ошибки находят потребители | DQ-gate и карантин до публикации | доля витрин с DQ ≥ 95 % |
| Эксплуатация | Разбирает инцидент | Долгий поиск причины | Метрики лага/DQ, lineage, трейс | MTTR DQ-инцидента ≤ 30 мин |
| Развитие | Меняет витрину | Страх сломать потребителей | Версионирование и rollback | 0 поломок обратной совместимости |

## Метрики CSI
- Опрос CSI разработчиков витрин (раз в квартал), целевой рост относительно текущего значения: +10 п.п.
- time-to-first-datamart: ≤ 1 рабочего дня (сейчас замеряется базово перед запуском фичи).
- Доля витрин с включёнными DQ-проверками: ≥ 95 % за два квартала после релиза.
"""


def architecture(p, obs, artifacts, faulty):
    e = obs["select_engine"][0]
    diagram = obs["mermaid_flow"][0]["mermaid"]
    why = "\n".join(f"- {x}" for x in e["rationale"])
    if e["ingest"] == "Flink":
        alt = ("- Альтернатива: Spark Structured Streaming вместо Flink — проще эксплуатация, но выше задержка; "
               "отвергнуто из-за SLA.")
    else:
        alt = (f"- Альтернатива: Flink вместо Spark — ниже задержка, но при SLA {p['freshness_sla_seconds']} с "
               "это избыточная сложность; отвергнуто.")
    return f"""# HLD: {p['title']}

## Контекст и цели
Фича встраивается в фреймворк витрин как новый слой: описание → загрузка → DQ-gate → публикация.
Цель — сократить time-to-first-datamart и количество инцидентов качества; SLA свежести {p['freshness_sla_seconds']} с.

Выбранный контур: ingest={e['ingest']}; serving={e['serving']}; batch={e['batch']}

## Компоненты
| Компонент | Ответственность | Технология |
|---|---|---|
| Config Service | Валидация и версионирование YAML, генерация DDL | Python / FastAPI |
| Ingest | Инкрементальная загрузка, event-time, watermarks | {e['ingest']} |
| DQ-gate | Исполнение правил до публикации, карантин | {e['ingest']} SQL / UDF |
| Serving | Хранение витрины и выдача потребителям | {e['serving']} — {e['serving_detail']} |
| Backfill | Пересчёт истории без остановки потока | {e['batch']} + Airflow |
| Quarantine | Отклонённые записи с причиной | HDFS (Parquet) |
| Observability | Метрики лага/DQ, lineage | Prometheus / каталог данных |

## Диаграмма
```mermaid
{diagram}
```

## Выбор технологий и trade-offs
{why}
{alt}
- Альтернатива: проверки внутри хранилища после загрузки — проще, но «битые» данные уже видны потребителям.

## Отказоустойчивость
| Сбой | Поведение | Восстановление |
|---|---|---|
| Падение Flink-джоба | Рестарт с checkpoint, повторная обработка | Идемпотентный upsert по ключу и версии |
| Недоступность {e['serving']} | Буферизация в Kafka, рост лага | Алерт по лагу > SLA, автоматический догон |
| Всплеск нарушений DQ | Строки уходят в Quarantine, витрина жива | Алерт владельцу, повторная обработка после фикса |
| Ошибка в новой конфигурации | Версия не активируется | Rollback на предыдущую версию |
"""


def requirements(p, obs, artifacts, faulty):
    rules = obs["suggest_dq_rules"][0]["rules"]
    rules_txt = "\n".join(f"- `{r['column']}` — {r['rule']} ({r['severity']})" for r in rules)
    nfr3 = ("| НФТ-03 | Производительность | высокая и стабильная |" if faulty else
            f"| НФТ-03 | Конкурентность запросов | ≥ {p['concurrent_users']} одновременных, p95 ≤ 3 с |")
    return f"""# Требования: {p['title']}

## Функциональные требования (ФТ)
| ID | Требование | Приоритет |
|---|---|---|
| ФТ-01 | Декларативное описание витрины в YAML (источники, ключ, SLA, DQ) с валидацией схемы при коммите | Must |
| ФТ-02 | Инкрементальная загрузка по ключу и event_ts с идемпотентной записью (upsert) | Must |
| ФТ-03 | Автогенерация DDL целевой таблицы из конфигурации | Must |
| ФТ-04 | DQ-gate: critical-нарушение → строка в карантин, warning → метрика и алерт | Must |
| ФТ-05 | Карантин отклонённых записей с причиной и возможностью повторной обработки | Must |
| ФТ-06 | Backfill за период без остановки потоковой загрузки | Should |
| ФТ-07 | Публикация метрик свежести и DQ в мониторинг | Must |
| ФТ-08 | Автоматический lineage источник → витрина → потребитель | Should |
| ФТ-09 | Маскирование PII-колонок по данным каталога | Must |
| ФТ-10 | Откат версии конфигурации витрины без потери данных | Should |

## Нефункциональные требования (НФТ)
| ID | Характеристика | Порог |
|---|---|---|
| НФТ-01 | Свежесть данных | p95 задержки событие → витрина ≤ {p['freshness_sla_seconds']} с |
| НФТ-02 | Пиковая нагрузка | выдерживает ×{p['peak_factor']:g} от среднего потока без роста лага |
{nfr3}
| НФТ-04 | Доступность чтения витрины | ≥ 99.9 % в месяц |
| НФТ-05 | Восстановление | RTO ≤ 30 мин, RPO ≤ 5 мин |
| НФТ-06 | Обратная совместимость | 100 % существующих конфигураций валидны без правок |
| НФТ-07 | Безопасность | 100 % PII-колонок замаскированы, доступ только по RBAC |
| НФТ-08 | Хранение | retention {p['retention_days']} дней, удаление по TTL автоматически |

## Приложение: DQ-правила по умолчанию
{rules_txt}
"""


def tz(p, obs, artifacts, faulty):
    ids = sorted(set(REQ_ID.findall(artifacts.get("requirements", ""))),
                 key=lambda i: (i.startswith("НФТ"), int(i.split("-")[1])))
    m = re.search(r"ingest=(\w+); serving=(\w+); batch=(\w+)", artifacts.get("architecture", ""))
    ingest, serving, batch = m.groups() if m else ("?", "?", "?")
    trace = "\n".join(
        f"| {i} | {'нагрузочный тест / мониторинг SLO' if i.startswith('НФТ') else 'автотест (интеграционный)'} |"
        for i in ids)
    return f"""# Техническое задание: {p['title']}

## 1. Цель и границы
Реализовать во фреймворке витрин декларативное описание, инкрементальную загрузку и DQ-gate.
Технологический контур (из HLD): {ingest} → {serving}, backfill — {batch}.
Вне границ: эволюция схем источников, UI-конструктор витрин.

## 2. Требования
Реализация обязана покрывать все требования, подтверждение — по таблице трассировки.

| Требование | Способ проверки |
|---|---|
{trace}

## 3. Критерии приёмки
- Витрина из примера (orders_events + customers_dim) поднимается из одного YAML без кастомного кода.
- p95 задержки событие → витрина ≤ {p['freshness_sla_seconds']} с на тестовом потоке с пиком ×{p['peak_factor']:g}.
- Критичные нарушения DQ не попадают в витрину и видны в карантине с причиной.
- Существующие конфигурации витрин проходят валидацию без изменений.

## 4. План тестирования и демо
1. Unit/контрактные тесты парсера конфигурации и генератора DDL.
2. Интеграционный стенд: поток событий с внедрёнными дефектами (null-ключ, отрицательная сумма, будущая дата).
3. Нагрузочный прогон: пик ×{p['peak_factor']:g}, {p['concurrent_users']} параллельных запросов.
4. Chaos-проверка: убить джоб, убедиться в догоне без дублей.
5. Демо для центров компетенций: путь пользователя по CJM от YAML до дашборда качества.

## 5. Пользовательская документация
- Quick start: первая витрина за один рабочий день.
- Справочник YAML-конфигурации и каталога DQ-правил.
- Runbook: лаг, карантин, откат конфигурации.
- Руководство миграции существующих витрин.
"""


_RENDERERS = {"research": research, "cjm": cjm, "architecture": architecture,
              "requirements": requirements, "tz": tz}


def render(stage, params, obs, artifacts, faulty) -> str:
    return _RENDERERS[stage](params, obs, artifacts, faulty)
